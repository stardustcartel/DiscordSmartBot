const assert = require("node:assert/strict");
const fs = require("node:fs"), os = require("node:os"), path = require("node:path");
const { KnowledgeBase, terms } = require("../src/knowledge");
const { partition, limits } = require("../src/knowledge-groups");
const { KnowledgeRetrieval, cite } = require("../src/knowledge-retrieval");
const { KnowledgeIndexer } = require("../src/knowledge-indexer");
const { budgetGroups, diverseCandidates } = require("../src/knowledge-search");
const { errorDetails } = require("../src/knowledge-errors");
const dir = fs.mkdtempSync(path.join(os.tmpdir(), "smartbot-groups-"));
const guildId = "100000000000000001", channelId = "100000000000000002", otherId = "100000000000000003";
const start = 1700000000000;
const settings = { get: () => ({ knowledgeChannelIds: [channelId, otherId], aiProvider: "openai", openAiModel: "test-model" }) };
let store = new KnowledgeBase({ dataDirectory: dir }, settings);
const raw = (id, content, extra = {}) => ({ id: String(id), guildId, channelId, rootId: channelId, channelName: "hardware", authorId: "alice", createdTimestamp: start + Number(id) * 1000, content, ...extra });
const get = (id) => store.groups.forMessage(raw(id, ""));
const ids = (group) => group.members.map((m) => m.id);
async function main() {
  const messages = [raw(100, "Watch the thermal settings."), raw(110, "I tested this on my machine."), raw(120, "Airflow was restricted by the case."), raw(130, "Opening the vents reduced temperatures.")];
  assert.equal(partition(messages).length, 1);
  assert.equal(partition([messages[0], { ...messages[1], authorId: "bob" }, messages[2]]).length, 3);
  assert.equal(partition([messages[0], { ...messages[1], content: "" }, messages[2]]).length, 2);
  assert.equal(partition([messages[0], { ...messages[1], channelId: otherId }]).length, 2);
  assert.equal(partition([messages[0], { ...messages[1], createdTimestamp: messages[0].createdTimestamp + limits.gapMs + 1 }]).length, 2);
  assert.equal(partition(Array.from({ length: 9 }, (_, n) => raw(n + 1, "one"))).length, 2);
  assert.equal(partition([raw(1, "x".repeat(5000)), raw(2, "y".repeat(4000))]).length, 2);
  assert.equal(partition([raw(1, "a", { replyToId: "50" }), raw(2, "b", { replyToId: "60" })]).length, 2);
  assert.equal(partition([raw(1, "a"), raw(2, "b", { replyToId: "1" })]).length, 1);
  const span = Array.from({ length: 8 }, (_, n) => raw(n + 1, "one", { createdTimestamp: start + n * 100000 }));
  assert.equal(partition(span).length, 2, "Long runs are bounded even when each gap is small");

  for (const row of [...messages].reverse()) store.store(row);
  assert.deepEqual(ids(get(120)), ["100", "110", "120", "130"], "Out-of-order backfill produces chronological groups");
  const result = store.groups.search("thermal airflow", terms("thermal airflow"), guildId, [channelId]);
  assert.equal(result.matches.length, 1, "AND terms can match across consecutive messages");
  assert.equal(result.unit, "conversation_group");
  assert.equal(store.groups.search("thermal", terms("thermal"), guildId, [otherId]).matches.length, 0);
  assert.equal(store.groups.search("thermal", terms("thermal"), "different-server", [channelId]).matches.length, 0);
  const vector = [1, 0, 0];
  const original = get(100);
  store.groups.putVector(original, "test-vector", vector);
  assert.equal((await store.groups.semantic(vector, "test-vector", guildId, [channelId])).length, 1);
  store.store({ ...messages[2], content: "Airflow was blocked by dust.", editedTimestamp: start + 999999 });
  assert.equal((await store.groups.semantic(vector, "test-vector", guildId, [channelId])).length, 0, "Editing a continuation invalidates the group vector");
  store.groups.putVector(original, "test-vector", vector);
  assert.equal((await store.groups.semantic(vector, "test-vector", guildId, [channelId])).length, 0, "An in-flight stale vector cannot overwrite an edit");
  store.remove(messages[1]);
  assert.deepEqual(ids(get(100)), ["100", "120", "130"]);
  store.store(messages[1]);
  store.store(messages[2]);
  store.store(raw(115, "Another person's interruption", { authorId: "bob" }));
  assert.deepEqual(ids(get(100)), ["100", "110"]);
  assert.deepEqual(ids(get(120)), ["120", "130"]);
  store.remove(raw(115, ""));
  assert.deepEqual(ids(get(100)), ["100", "110", "120", "130"]);
  store.groups.boundary({ id: "115", guildId, channelId, author: { id: "bot" }, createdTimestamp: start + 115000 });
  assert.deepEqual(ids(get(100)), ["100", "110"], "Excluded messages break adjacency without indexing their content");
  store.remove({ id: "115" });
  assert.deepEqual(ids(get(100)), ["100", "110", "120", "130"]);
  store.groups.boundary({ id: "115", guildId, channelId, channel: { parentId: "category", isThread: () => false }, author: { id: "bot" }, createdTimestamp: start + 115000 });
  store.prune(guildId);
  assert.deepEqual(ids(get(100)), ["100", "110"], "Pruning preserves excluded-message boundaries in categorized text channels");
  store.remove({ id: "115" });
  store.groups.putVector(get(100), "test-vector", vector);
  store.close(); store = new KnowledgeBase({ dataDirectory: dir }, settings);
  assert.deepEqual(ids(get(100)), ["100", "110", "120", "130"]);
  assert.equal((await store.groups.semantic(vector, "test-vector", guildId, [channelId])).length, 1, "Restart keeps derived vectors");
  assert.equal(diverseCandidates([result.matches], "thermal", "120").length, 0, "Never retrieve the user's own prompt as part of a group");
  assert.equal(budgetGroups([get(100)], 10).selected.length, 0, "Budget does not truncate a group");
  assert.equal(budgetGroups([get(100)], 10000, 3).selected.length, 0, "Message budget is also atomic");

  const live = new Map();
  const channel = { id: channelId, guildId, name: "hardware", type: 0, isThread: () => false };
  const liveMessage = (row) => ({ id: row.id, guildId, channelId, channel, author: { id: row.authorId, bot: false }, content: row.content, createdTimestamp: row.createdTimestamp, editedTimestamp: row.editedTimestamp || null });
  for (const row of messages) live.set(row.id, liveMessage(row));
  channel.messages = { fetch: async (options) => options.message ? live.get(options.message) : new Map(live) };
  const access = { allowedIds: [channelId], safeRoots: new Set([channelId]), decisions: new Map(), destination: channel,
    guild: { id: guildId, channels: { cache: new Map([[channelId, channel]]), fetch: async () => channel } } };
  const indexer = { scan: async () => {}, credentials: () => ({ provider: "openai", apiKey: "NEVER_LOG_THIS", model: "test-model" }), cooldowns: new Map([[guildId, Date.now() + 600000]]) };
  let failReview = true;
  const ai = { generate: async (options) => {
    options.onModelAttempt?.("test-model");
    if (options.textFormat.name === "knowledge_search_plan") return JSON.stringify({ concepts: ["thermal"], queries: [{ query: "thermal", channelIds: [], offset: 0 }] });
    const input = JSON.parse(options.conversation[0].text);
    assert.equal(input.candidates.find((g) => g.id === "100").messages.length, 4, "Reviewer sees all continuations");
    if (failReview) throw Object.assign(new Error("NEVER_LOG_THIS"), { name: "AbortError", code: 20 });
    return JSON.stringify({ sufficient: true, explanation: "Whole explanation", selections: [{ id: "100", reason: "Test experience" }], queries: [] });
  } };
  const retrieval = new KnowledgeRetrieval(store, indexer, ai);
  // Access checks are covered by the existing permission suite. Here isolate group
  // lifecycle and the full prepare/search pipeline with real SQLite and fake Discord.
  retrieval.access = async () => access;
  retrieval.validate = async (_, __, rows) => rows;
  const traces = [];
  retrieval.writeTrace = (_, trace) => traces.push(trace);
  const request = { guildId, channelId, userId: "tester", text: "Any thermal advice?", messageId: "999" };
  const prepared = await retrieval.prepare(request);
  assert.deepEqual(prepared.sources.map((m) => m.id), ["100", "110", "120", "130"], "Timeout fallback retains the complete explanation");
  assert.deepEqual(prepared.records.map((r) => r.groupId), ["100", "100", "100", "100"]);
  assert.ok(prepared.context.includes(messages[3].content));
  assert.equal(traces[0].searchOutcome, "relevance_review_unavailable");
  assert.equal(traces[0].searchRounds[0].review.error.kind, "timeout_or_abort");
  assert.deepEqual(traces[0].aiCalls[1].modelAttempts, ["test-model"]);
  assert.ok(!JSON.stringify(traces).includes("NEVER_LOG_THIS"));
  assert.ok(cite("Explanation [S3]", prepared.sources).endsWith(`/channels/${guildId}/${channelId}/120)`), "Each citation targets the actual supporting message");
  failReview = false;
  assert.deepEqual((await retrieval.prepare(request)).sources.map((m) => m.id), prepared.sources.map((m) => m.id), "Successful review and fallback both keep complete groups");

  const group = get(100);
  live.set("115", { ...liveMessage(raw(115, "")), author: { id: "bot", bot: true } });
  const boundaryTrace = {};
  const regrouped = await retrieval.validateGroups(null, access, [group], { trace: boundaryTrace });
  assert.deepEqual(ids(regrouped[0]), ["100", "110"], "Live history discovers a previously unindexed bot interruption");
  assert.equal(boundaryTrace.liveGroupChecks[0].membershipChanged, true);
  assert.equal(retrieval.groupsUnchanged(prepared.sources), false, "Group changes invalidate an in-flight draft");
  live.delete("115"); store.remove({ id: "115" });
  live.delete("120");
  const deleted = await retrieval.validateGroups(null, access, [get(100)]);
  assert.deepEqual(ids(deleted[0]), ["100", "110", "130"], "Deleted continuations are not quoted");
  retrieval.validate = async (_, __, rows) => rows.filter((m) => m.id !== "130");
  assert.equal((await retrieval.validateGroups(null, access, [get(100)])).length, 0, "Do not retain partial groups when member access cannot be verified");
  assert.equal(errorDetails(Object.assign(new Error("secret"), { status: 429 })).httpStatus, 429);
  assert.ok(!JSON.stringify(errorDetails(new Error("secret"))).includes("secret"));
  const originalFetch = globalThis.fetch;
  try {
    const productionIndexer = new KnowledgeIndexer(store, settings, { getOpenAiKey: () => "fake", getGeminiKey: () => "fake" });
    productionIndexer.discover = async () => [];
    channel.permissionsFor = () => ({ has: () => true });
    access.guild.members = { me: {} };
    let embeddedInputs = [];
    globalThis.fetch = async (_, options) => {
      embeddedInputs = JSON.parse(options.body).input;
      const embedding = Array(768).fill(0); embedding[0] = 1;
      return { ok: true, json: async () => ({ data: embeddedInputs.map((__, index) => ({ index, embedding })) }) };
    };
    await productionIndexer.tick({ guilds: { cache: new Map([[guildId, access.guild]]) } });
    assert.equal(embeddedInputs.length, 1, "Background indexer embeds the group, not each split message");
    assert.ok(embeddedInputs[0].includes(messages[3].content));
    assert.equal(productionIndexer.statuses[guildId].embedded, 3, "Dashboard coverage counts all embedded group members");
  } finally { globalThis.fetch = originalFetch; }
  store.removeChannel(channelId); store.groups.flush(guildId);
  assert.equal(store.db.prepare("SELECT count(*) AS n FROM conversation_groups").get().n, 0);
  console.log("Conversation grouping, split-term search, group vectors, edits/deletes/backfill, boundaries, timeout fallback, live regrouping, budgets, citations and safe logs passed.");
}
main().catch((error) => { console.error(error); process.exitCode = 1; }).finally(() => { store.close(); fs.rmSync(dir, { recursive: true, force: true }); });
