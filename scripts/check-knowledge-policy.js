const assert = require("node:assert/strict");
const { normalizePolicy, effectivePolicy, trustedClock, directClockAnswer, evidenceInstructions, validateEvidenceReview } = require("../src/knowledge-policy");
const { GuildSettingsStore } = require("../src/guild-settings");
const forum = "100000000000000001", thread = "100000000000000002", other = "100000000000000003";
const defaults = normalizePolicy();
assert.equal(defaults.knowledgeOnly, false);
assert.equal(defaults.requireCitations, false);
const policy = { knowledgeOnly: true, requireCitations: true, citationCount: 2, generalChannels: [forum], uncitedChannels: [other] };
const inForum = effectivePolicy(policy, { id: thread, parentId: forum, isThread: () => true });
assert.equal(inForum.knowledgeOnly, false);
assert.equal(inForum.requireCitations, true);
const inOther = effectivePolicy(policy, { id: other, isThread: () => false });
assert.equal(inOther.knowledgeOnly, true);
assert.equal(inOther.requireCitations, false);
assert.equal(effectivePolicy(policy, { id: "elsewhere", parentId: forum, isThread: () => false }).knowledgeOnly, true, "Category ID is not a forum exemption");
assert.equal(normalizePolicy({ knowledgeOnly: "true", citationCount: 99 }).knowledgeOnly, false);
assert.equal(normalizePolicy({ citationCount: 99 }).citationCount, 3);
const clock = new Date("2026-10-08T19:20:30Z");
assert.ok(trustedClock(clock).includes("2026-10-08"));
for (const question of ["What is the current date/time?", "what time is it?", "what day is today?", "what's the date today?"]) {
  const answer = directClockAnswer(question, clock);
  assert.ok(answer?.includes("October 8, 2026") && answer.includes("UTC"), question);
}
for (const question of ["What time is the Q&A tonight?", "What date was the announcement posted?", "What time is it in Tokyo?"]) assert.equal(directClockAnswer(question, clock), null);
const instructions = evidenceInstructions(policy);
assert.ok(instructions.includes("postedAt") && instructions.includes("No live internet") && instructions.includes("up to 2"));
const records = [{ id: "S1", content: "The Q&A is tonight at 8 p.m. Eastern.", postedAt: "2026-09-09T12:00:00Z" }];
const review = { kind: "grounded", supported: true, answer: "The September 9 post scheduled a Q&A for that evening; it does not establish today's schedule. [S1]", evidence: [{ id: "S1", quote: "The Q&A is tonight at 8 p.m. Eastern." }] };
assert.equal(validateEvidenceReview(review, records, policy), review.answer, "Fewer citations is correct when fewer sources support answer");
assert.equal(validateEvidenceReview({ ...review, answer: "Today is September 9 [S999]" }, records, policy), null);
assert.equal(validateEvidenceReview({ ...review, evidence: [{ id: "S1", quote: "Today is October 8." }] }, records, policy), null);
assert.equal(validateEvidenceReview({ ...review, supported: false }, records, policy), null);
assert.equal(validateEvidenceReview({ ...review, answer: "No citation" }, records, policy), null);
assert.equal(validateEvidenceReview({ ...review, kind: "general", answer: "General advice" }, records, policy), null, "General knowledge forbidden in strict mode");
assert.ok(validateEvidenceReview({ ...review, kind: "general", answer: "General advice" }, records, { ...policy, knowledgeOnly: false }).startsWith("General information"));
assert.equal(validateEvidenceReview({ kind: "abstain", supported: true, answer: "I cannot verify that." }, [], policy), "I cannot verify that.");
const manyRecords = Array.from({ length: 3 }, (_, i) => ({ id: `S${i + 1}`, content: `Evidence number ${i + 1}` }));
assert.equal(validateEvidenceReview({ kind: "grounded", supported: true, answer: "Answer [S1] [S2] [S3]", evidence: manyRecords.map((r) => ({ id: r.id, quote: r.content })) }, manyRecords, policy), null, "Citation cap enforced");
const store = Object.create(GuildSettingsStore.prototype);
store.config = { defaultReminderTimeZone: "UTC", defaultAiResponsesPerHour: 30 }; store.defaultPersonality = "Helpful";
assert.deepEqual(store.normalize({ knowledgePolicy: policy }).knowledgePolicy, policy, "Oracle normalization must preserve synced policy");
assert.deepEqual(store.normalize({}).knowledgePolicy, defaults, "Existing servers stay opt-in");
console.log("Knowledge defaults, independent/forum exceptions, trusted clock, evidence/citation checks, and sync normalization passed.");
