const assert = require('node:assert/strict');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
const { KnowledgeBase } = require('../src/knowledge');
const { KnowledgeRetrieval } = require('../src/knowledge-retrieval');
const { KnowledgeIndexer } = require('../src/knowledge-indexer');
const { readGroupWindows } = require('../src/knowledge-live');
const { SOURCE_POLICY_VERSION } = require('../src/knowledge-message');
const { AiChat } = require('../src/ai');
const { retryDelay } = require('../src/gemini-model-status');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'smartbot-workflow-'));
const guildId = '100000000000000001', channelId = '100000000000000002';
const bot = { id: 'self', bot: true }, member = { id: 'reader' }, live = new Map();
const settings = { knowledgeChannelIds: [channelId] };
const store = new KnowledgeBase({ dataDirectory: directory }, { get: () => settings });
let readable = true, channelReads = 0, historyReads = 0;
const guild = { id: guildId, members: { me: bot } };
const channel = { id: channelId, guildId, guild, name: 'general', type: 0, isThread: () => false,
  permissionsFor: () => ({ has: () => readable }), messages: { fetch: async options => {
    if (options.message) return live.get(options.message);
    historyReads++;
    let rows = [...live.values()].filter(m => (!options.before || BigInt(m.id) < BigInt(options.before)) && (!options.after || BigInt(m.id) > BigInt(options.after)));
    rows.sort((a,b) => options.after ? Number(a.id)-Number(b.id) : Number(b.id)-Number(a.id));
    if (options.around) {
      rows.sort((a,b) => Number(a.id)-Number(b.id));
      const at = rows.findIndex(m => m.id === options.around);
      rows = rows.slice(Math.max(0, at-49), Math.max(0, at-49)+options.limit);
    } else rows = rows.slice(0,options.limit);
    return new Map(rows.map(m => [m.id,m]));
  } } };
guild.channels = { fetch: async () => { channelReads++; return channel; } };
const access = { guild, member, bot, destination: { isServerDm: true } };
const message = id => ({ id:String(id), guildId, channelId, channel, guild, author:{id:'author-'+id,bot:false}, content:'Useful experience '+id, createdTimestamp:id*1000 });
(async () => {
  store.transaction(() => { for(let id=1000;id<1100;id++){const m=message(id);live.set(m.id,m);store.upsert(m);} });
  store.groups.flush(guildId);
  const excluded = { ...message(1015), author:bot, content:'Earlier assistant answer' };
  store.upsert(excluded);store.groups.flush(guildId);
  const changes = store.db.prepare('SELECT total_changes() AS n').get().n;
  for(let n=0;n<20;n++){store.upsert(excluded);store.upsert(live.get('1020'));}
  assert.equal(store.db.prepare('SELECT total_changes() AS n').get().n,changes,'Unchanged messages and excluded boundaries do not rewrite SQLite/FTS or dirty groups');
  assert.equal(store.db.prepare('SELECT count(*) AS n FROM knowledge_group_dirty').get().n,0);
  const groups = Array.from({length:24},(_,n)=>store.groups.forMessage({id:String(1020+n),guildId,channelId}));
  const retrieval = new KnowledgeRetrieval(store,{},{}), trace={};
  const valid = await retrieval.validateGroups(null,access,groups,{trace});
  assert.deepEqual(valid.map(g=>g.id),groups.map(g=>g.id),'Batching preserves source IDs and order');
  assert.equal(historyReads,1,'Overlapping source groups share one history window');
  assert.equal(trace.liveGroupTiming.reusedWindows,23);
  assert.equal(channelReads,2,'Channel access is checked before and after the history batch');
  live.get('1020').content='Changed experience';
  assert.equal((await retrieval.validateGroups(null,access,[groups[0]]))[0].content,'Changed experience','A new validation pass sees edits');
  live.delete('1021');
  assert.equal((await retrieval.validateGroups(null,access,[groups[1]])).length,0,'Deleted anchors are rejected');
  assert.equal(store.db.prepare('SELECT id FROM messages WHERE id=?').get('1021'),undefined);
  const originalFetch=channel.messages.fetch;
  channel.messages.fetch=async options=>{const batch=await originalFetch(options);readable=false;return batch;};
  assert.equal((await retrieval.validateGroups(null,access,[groups[2]])).length,0,'Permission revocation during history fetching is rejected');
  readable=true;channel.messages.fetch=originalFetch;
  historyReads=0;
  const indexer = new KnowledgeIndexer(store,store.guildSettings,{});
  channel.lastMessageId='1099';
  store.checkpoint(`channel:${channelId}`,{guildId,rootId:channelId,id:channelId,latest:'1099',before:'1000',complete:true,caughtUp:true,checkedAt:1,sourcePolicyVersion:SOURCE_POLICY_VERSION});
  await indexer.scan(channel,true);
  assert.equal(historyReads,1,'A latest page covering the checkpoint needs no duplicate delta fetch');
  await indexer.scan(channel,true);
  assert.equal(historyReads,2,'Each catch-up still reads a fresh latest page');
  live.set('1110',message(1110));channel.lastMessageId='1110';
  await indexer.scan(channel,true);
  assert.equal(historyReads,3,'New messages are caught by the fresh latest page');
  assert.ok(store.db.prepare('SELECT id FROM messages WHERE id=?').get('1110'));

  let active=0,maximum=0;
  const separate=Array.from({length:7},(_,i)=>({id:String(i+5000),channelId:String(i),memberIds:[String(i+5000)]}));
  await readGroupWindows(separate,async id=>({messages:{fetch:async()=>{
    active++;maximum=Math.max(maximum,active);await new Promise(resolve=>setImmediate(resolve));active--;
    return new Map([[String(Number(id)+5000),{}]]);
  }}}),{});
  assert.equal(maximum,3,'History concurrency is bounded across channels');
  let attempts=[],firstLimited=true,secondFails=false;
  const ai=new AiChat({dataDirectory:directory,geminiModels:['first','second']});
  ai.getClient=()=>({models:{generateContent:async({model})=>{
    attempts.push(model);
    if(model==='first'&&firstLimited)throw Object.assign(new Error('Retry after 2s'),{status:429});
    if(model==='second'&&secondFails)throw Object.assign(new Error('unavailable'),{status:503});
    return{text:model+' answer'};
  }}});
  const args={provider:'gemini',apiKey:'key-one',scopeId:guildId,conversation:[{role:'user',text:'question'}]};
  await ai.generate(args);assert.deepEqual(attempts,['first','second']);
  attempts=[];await ai.generate(args);assert.deepEqual(attempts,['second'],'A known limited model is not retried before an available model');
  attempts=[];firstLimited=false;secondFails=true;
  assert.equal(await ai.generate(args),'first answer','Fallback probes a cooling model if ready models fail');
  assert.deepEqual(attempts,['second','first']);
  attempts=[];secondFails=false;await ai.generate({...args,apiKey:'replacement'});assert.equal(attempts[0],'first','Key replacement resets retry observations');
  ai.geminiStatus.observe(guildId,'replacement','first','limit');
  ai.geminiStatus.state(guildId,'replacement').models.first.retryUntil=Date.now()-1;
  attempts=[];await ai.generate({...args,apiKey:'replacement'});assert.equal(attempts[0],'first','Expired cooldown restores the highest-priority model');
  assert.equal(retryDelay({status:429,message:'{"retryDelay":"4.5s"}'},'limit'),4500);
  assert.equal(retryDelay({status:429,message:'RequestsPerDay limit'},'limit'),300000);
  assert.equal(retryDelay(null,'success'),0);
  assert.ok(!fs.readFileSync(path.join(directory,'gemini-model-status.json'),'utf8').includes('key-one'));
  console.log('Workflow latency checks passed: 24 source groups use 1 history read (23 reused), fresh permission/edit/delete checks, no-op indexing, complete catch-up, bounded concurrency and Gemini retry recovery.');
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(()=>{store.close();fs.rmSync(directory,{recursive:true,force:true});});
