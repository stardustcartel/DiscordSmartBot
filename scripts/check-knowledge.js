const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { Collection, PermissionsBitField } = require("discord.js");
const { KnowledgeBase } = require("../src/knowledge");
const { KnowledgeIndexer } = require("../src/knowledge-indexer");
const { KnowledgeRetrieval, mergeRankings, cite } = require("../src/knowledge-retrieval");
const { safeAudience } = require("../src/knowledge-permissions");
