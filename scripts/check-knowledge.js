  globalThis.fetch = async () => ({ ok: false, status: 429 });
  const fallback = await fullRetrieval.prepare({ client, guildId, channelId: otherRoot, userId, text: "portraits lens" });
  assert.ok(fallback.sources.some((m) => m.id === guidance.id), "Embedding outage retains keyword retrieval");
  assert.equal(cite("Read [S1] [S999]", [{ url: "https://discord.com/channels/1/2/3" }]), "Read [source 1](https://discord.com/channels/1/2/3) ");
  assert.equal(mergeRankings([[{ message: { id: "a" } }], [{ message: { id: "a" } }, { message: { id: "b" } }]])[0].message.id, "a");
  globalThis.fetch = async (_, opts) => {
    const body = JSON.parse(opts.body);
    assert.equal(body.dimensions, 768);
    return { ok: true, json: async () => ({ data: body.input.map((_, index) => ({ index, embedding: vector })) }) };
  };
  assert.equal((await embed({ provider: "openai", apiKey: "fake", texts: ["camera"] }))[0].length, 768);
  globalThis.fetch = async () => ({ ok: false, status: 429 });
  await assert.rejects(embed({ provider: "openai", apiKey: "fake", texts: ["camera"] }), /keyword search remains/);
  const requests = [];
  globalThis.fetch = async (_, opts) => { requests.push(JSON.parse(opts.body)); return { ok: true, json: async () => ({ output_text: "Answer [S1]" }) }; };
  const ai = new AiChat({ defaultAiResponsesPerHour: 30 });
  const args = { apiKey: "fake", provider: "openai", scopeId: guildId, userId, text: "question", personality: "Be cheerful" };
  await ai.respond({ ...args, conversationId: "one", context: "PRIVATE EVIDENCE", forgetHistory: true });
