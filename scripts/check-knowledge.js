  globalThis.fetch = async () => ({ ok: true, json: async () => ({ data: [{ index: 0, embedding: vector }] }) });
  const prepared = await fullRetrieval.prepare({ client, guildId, channelId: otherRoot, userId, text: "what glass do i need for headshots?" });
